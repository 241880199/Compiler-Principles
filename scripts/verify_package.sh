#!/usr/bin/env bash
# 交付包复核：把 zip 解到临时目录，用**两条**构建路径各自从零构建，再与仓库构建逐字节对拍。
#
#   用法： bash scripts/verify_package.sh <zip>
#   环境： PKG_REF_MAKEFILE=<路径>   判分机用的参考 Makefile（缺省 ../Makefile_ref）
#
# 为什么是"对拍"而不是"再比对一遍 .exp"：
#   仓库自检 scripts/run_tests.sh 已经把仓库的 ./parser 钉在全部 .exp 上（75 个全过）。
#   本脚本只要证明**包里的构建与仓库的构建逐字节同行为**，结论就传递过去了 ——
#   于是这里不存在第二份期望值，也就不会出现"两份期望各自漂移"的问题。
#
# 为什么要测**两条**构建路径：
#   判分机不用我们包里的 Makefile，它把课程给的参考 Makefile 盖上去再 `make`。
#   2026-09-23 首次提交就栽在这里：参考 Makefile 的链接行把 `lex.yy.o` 滤掉，
#   于是扫描器压根没进链接，报 `undefined reference to 'yylex'`。
#   而**本脚本当时只测了我们自己那份 Makefile** —— 判据测的不是判分机真正跑的东西。
#   故 ⑤ 专门复现判分机那条路（摊平源码 + 参考 Makefile）。
#
# 断言清单（每条都对应一种真实发生过的失效）：
#   ① 条目清单 —— 交付包里混进过无关文件；反过来，**少一个文件**（如扫描器 .c）会让
#      判分机链接失败。故清单是逐项双向比对的。
#   ② 包内 report.pdf 与仓库那份逐字节相同 —— 报告现场排版，容易"改了 .tex 忘重编"。
#   ③ Code/lexer.c 确实是 flex 产物（文件在、内容是空的也会让判分机链接失败）。
#   ④/⑤ 自建 Makefile 路径：干净目录 make 零 gcc 警告、两个运行入口在、冲突数恰好 3、
#      与仓库构建逐字节对拍。
#   ⑥ 参考 Makefile 路径（判分机真正走的那条）：同样从零构建 + 冲突数 + 对拍。
#   ⑦ 守卫：一个用例都没跑到就报红（语料被清空时"0 个不一致"也会打印成功）。
set -euo pipefail

cd "$(dirname "$0")/.."
REPO=$PWD
ZIP=$(realpath -m "${1:?用法: bash scripts/verify_package.sh <zip>}")
REF_MK=$(realpath -m "${PKG_REF_MAKEFILE:-$REPO/../Makefile_ref}")

if [ ! -f "$ZIP" ]; then
    echo "错误：找不到 $ZIP" >&2
    exit 1
fi
if [ ! -f "$REF_MK" ]; then
    echo "错误：找不到判分机用的参考 Makefile：$REF_MK" >&2
    echo "      它是课程发的那份（实验一那批文件里的 Makefile_ref）。判分机正是用它与" >&2
    echo "      '摊平后的源码'一起 make，所以这条路径**必须**测；缺了它这个包就没被验过。" >&2
    echo "      用 PKG_REF_MAKEFILE=<路径> 指定别处。" >&2
    exit 1
fi

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "── 交付包复核：$(basename "$ZIP") ──"

# ── ① 条目清单：包内文件必须恰好是「预期的那一份」────────────────
# 预期 = report.pdf + Code/Makefile + Code/lexer.c（打包脚本现场生成的扫描器）
#        + HEAD 里 src/ 下的全部跟踪文件（平铺）。
# lab3 新增的 ir.c/ir.h/translate.c/translate.h/optimize.c/optimize.h 无需手写进
# 清单：它们只要被 git 跟踪，就会由下面的 `git ls-tree` 自动派生进来。解包后另有
# 一组显式存在性断言（见 ③ 之后）作双保险，防止“清单生成方式变了、新文件漏掉”。
{
    echo "report.pdf"
    echo "Code/Makefile"
    echo "Code/lexer.c"
    git ls-tree -r --name-only HEAD src | sed 's|^src/|Code/|'
} | sort > "$WORK/expected"
unzip -Z1 "$ZIP" | grep -v '/$' | sort > "$WORK/actual"

if ! diff -q "$WORK/expected" "$WORK/actual" > /dev/null; then
    echo "FAIL  包内条目与预期不符（左=预期，右=包内）："
    diff -u "$WORK/expected" "$WORK/actual" | sed 's/^/      /'
    exit 1
fi
echo "  ① 条目：$(wc -l < "$WORK/actual") 个，与预期一致"

unzip -q "$ZIP" -d "$WORK/unpacked"
PKG=$WORK/unpacked/Code

# ── ② 包内 report.pdf 必须是仓库当前那份 ───────────────────────
REPORT_PDF=docs/实验三报告.pdf
if [ ! -s "$REPORT_PDF" ]; then
    echo "FAIL  找不到 $REPORT_PDF —— 无法核对包内报告" >&2
    echo "      报告需现场排版：xelatex 编**两遍**（只编一遍页数不作数）。" >&2
    exit 1
fi
if ! cmp -s <(unzip -p "$ZIP" report.pdf) "$REPORT_PDF"; then
    echo "FAIL  包内 report.pdf 与 $REPORT_PDF 不一致" >&2
    echo "      多半是改了 .tex 却没重编，或包是上一版打的 —— 重新打包即可。" >&2
    exit 1
fi
echo "  ② report.pdf 与 $REPORT_PDF 逐字节一致（$(pdfinfo "$REPORT_PDF" | awk '/^Pages/{print $2}') 页）"

# ── 扫描器那一份也要像扫描器（防"文件在但内容是空的/不是 flex 产物"）──
if ! grep -q 'generated by flex' "$PKG/lexer.c"; then
    echo "FAIL  包内 Code/lexer.c 不像 flex 的产物（判分机链接会失败）" >&2
    exit 1
fi
echo "  ③ Code/lexer.c 是 flex 产物（$(wc -l < "$PKG/lexer.c") 行）"

# lab3 新增源文件必须随包（双保险）：上面的条目清单是自动派生的，这里再显式点名。
for f in ir.c ir.h translate.c translate.h optimize.c optimize.h; do
    [ -f "$PKG/$f" ] || { echo "FAIL  交付包缺 Code/$f" >&2; exit 1; }
done
echo "  ③+ lab3 源文件齐全：ir.c ir.h translate.c translate.h optimize.c optimize.h"

# ── 冲突数断言（两条构建路径共用）──────────────────────────────
check_conflicts() {   # $1 = 含 syntax.output 的目录, $2 = 标签
    local dir=$1 tag=$2 n one
    if [ ! -f "$dir/syntax.output" ]; then
        echo "FAIL  $tag：未生成 syntax.output —— 冲突数断言无法执行" >&2
        exit 1
    fi
    # 锚定匹配，非子串：`grep -c "conflicts:"` 会放过 "1 shift/reduce, 1 reduce/reduce"。
    # [Ss] 兼容 bison 3.0.4 的 `state` 小写。
    n=$(grep -cE '^[Ss]tate [0-9]+ conflicts:' "$dir/syntax.output" || true)
    one=$(grep -cE '^[Ss]tate [0-9]+ conflicts: 1 shift/reduce$' "$dir/syntax.output" || true)
    if [ "$n" -ne 3 ] || [ "$one" -ne 3 ]; then
        echo "FAIL  $tag：期望恰好 3 个冲突 state 且每个都是「1 shift/reduce」，实测 $n 个 / 其中 $one 个" >&2
        grep -nE '^[Ss]tate [0-9]+ conflicts:' "$dir/syntax.output" | sed 's/^/      /' >&2
        exit 1
    fi
}

# 只数**编译器**警告。判据锚在 gcc 的诊断格式上：bison 的
# `syntax.y: warning: 3 shift/reduce conflicts` 是**预期之内**的，不能算进来
# （用裸 `warning:` 计数会在正常构建上误报 —— 判据与它声称检验的东西不一致）。
count_gcc_warnings() {   # $1 = 构建日志
    grep -cE '^[^:]+\.(c|h):[0-9]+:[0-9]+: warning:' "$1" || true
}

# ── 与仓库构建对拍（两条路径共用）。$1 = 待测 parser，$2 = 标签 ──
DIFF_PASS=0
DIFF_FAIL=0
LAB2_RAN=0
diffrun() {
    local other=$1 label=$2 cmm abs rs ps
    DIFF_PASS=0; DIFF_FAIL=0; LAB2_RAN=0
    for cmm in Test/sample/*.cmm Test/err/*.cmm Test/lab2/*.cmm; do
        [ -e "$cmm" ] || continue
        case "$cmm" in Test/lab2/*) LAB2_RAN=$((LAB2_RAN + 1));; esac
        abs=$REPO/$cmm
        set +e
        "$REPO/parser" "$abs" > "$WORK/r.out" 2> "$WORK/r.err"; rs=$?
        "$other"       "$abs" > "$WORK/p.out" 2> "$WORK/p.err"; ps=$?
        set -e
        if [ "$rs" -ne "$ps" ]; then
            echo "FAIL  $cmm  （$label 退出码不一致：仓库 $rs vs 包 $ps）"
            DIFF_FAIL=$((DIFF_FAIL + 1))
        elif ! diff -q "$WORK/r.out" "$WORK/p.out" > /dev/null; then
            echo "FAIL  $cmm  （$label stdout 不一致）"
            diff -u "$WORK/r.out" "$WORK/p.out" | sed 's/^/      /' | head -20
            DIFF_FAIL=$((DIFF_FAIL + 1))
        elif ! diff -q "$WORK/r.err" "$WORK/p.err" > /dev/null; then
            echo "FAIL  $cmm  （$label stderr 不一致）"
            diff -u "$WORK/r.err" "$WORK/p.err" | sed 's/^/      /' | head -20
            DIFF_FAIL=$((DIFF_FAIL + 1))
        else
            DIFF_PASS=$((DIFF_PASS + 1))
        fi
    done
}

# ── ④ 自建 Makefile 路径 ───────────────────────────────────────
cd "$PKG"
if ! make clean > /dev/null 2>&1; then
    echo "FAIL  make clean 失败（包内 Makefile 的 clean 规则有问题）" >&2
    exit 1
fi
if ! make > "$WORK/build-own.log" 2>&1; then
    echo "FAIL  自建 Makefile：干净目录下 make 失败：" >&2
    tail -25 "$WORK/build-own.log" | sed 's/^/      /' >&2
    exit 1
fi
warn=$(count_gcc_warnings "$WORK/build-own.log")
if [ "$warn" -ne 0 ]; then
    echo "FAIL  自建 Makefile：gcc 警告 $warn 条（要求书与 README 都要求零警告）：" >&2
    grep -nE '^[^:]+\.(c|h):[0-9]+:[0-9]+: warning:' "$WORK/build-own.log" | sed 's/^/      /' >&2
    exit 1
fi
for bin in parser cc; do
    [ -x "$bin" ] || { echo "FAIL  自建 Makefile：缺可执行文件 ./$bin" >&2; exit 1; }
done
check_conflicts "$PKG" "自建 Makefile"
echo "  ④ 自建 Makefile：从零 make 通过、零 gcc 警告、./parser 与 ./cc 在、冲突数 3"

cd "$REPO"
make parser > /dev/null 2>&1 || { echo "FAIL  仓库自身构建失败，无法对拍" >&2; exit 1; }
diffrun "$PKG/parser" "自建"
[ "$DIFF_PASS" -ne 0 ] || { echo "FAIL  自建路径：一个用例都没跑到" >&2; exit 1; }
[ "$DIFF_FAIL" -eq 0 ] || { echo "FAIL  自建路径：$DIFF_FAIL 个用例与仓库构建不一致" >&2; exit 1; }
echo "  ⑤ 自建 Makefile 行为对拍：$DIFF_PASS 个用例逐字节一致"

# ── ⑥ 判分机那条路径：摊平源码 + 参考 Makefile ─────────────────
# 用户日志里源码是 `./lexical.l`、`./type.o` 这样的**平铺**形态，故这里也摊平 ——
# 判分机多半就是把提交摊平、盖上课给的 Makefile、然后 make。
JUDGE=$WORK/judge
mkdir -p "$JUDGE"
# **重新解一次包**再摊平：不能拿上面那份 $PKG —— 它已经被 ④ 构建过，带着 lex.yy.c 与
# 一堆 .o，会让这条路径跑成"增量构建"，从而掩盖"从零能不能编出来"。
unzip -q "$ZIP" -d "$WORK/judge-src"
cp "$WORK/judge-src/Code"/* "$JUDGE/"
cp "$REF_MK" "$JUDGE/Makefile"

# 参考 Makefile 的链接行固定带 `-ly`。判分镜像是 Ubuntu 20.04，bison 一装就带上
# liby，故那条命令在那边能过（用户日志里没有 "cannot find -ly"，只有 yylex/yyin 未定义）。
# 本机 WSL 没装 liby，直接跑会卡在 `-ly` —— 用一个**空归档**顶上，只为让那条固定命令
# 跑通；我们不引用 liby 的任何符号，故遮蔽真实 liby 无风险。
if ! printf 'int main(void){return 0;}\n' | gcc -x c - -o /dev/null -ly 2>/dev/null; then
    mkdir -p "$WORK/stublib" && ar rcs "$WORK/stublib/liby.a"
    export LIBRARY_PATH="$WORK/stublib${LIBRARY_PATH:+:$LIBRARY_PATH}"
    echo "  NOTE  本机缺 liby，用空归档顶上以跑通参考 Makefile 的固定链接行（判分机有 liby）"
fi

cd "$JUDGE"
if ! make clean > /dev/null 2>&1; then
    echo "FAIL  参考 Makefile：make clean 失败" >&2
    exit 1
fi
if ! make > "$WORK/build-ref.log" 2>&1; then
    echo "FAIL  参考 Makefile：干净目录下 make 失败（**这正是判分机上会发生的事**）：" >&2
    tail -25 "$WORK/build-ref.log" | sed 's/^/      /' >&2
    exit 1
fi
warn=$(count_gcc_warnings "$WORK/build-ref.log")
if [ "$warn" -ne 0 ]; then
    echo "FAIL  参考 Makefile：gcc 警告 $warn 条：" >&2
    grep -nE '^[^:]+\.(c|h):[0-9]+:[0-9]+: warning:' "$WORK/build-ref.log" | sed 's/^/      /' >&2
    exit 1
fi
[ -x "$JUDGE/parser" ] || { echo "FAIL  参考 Makefile：没有产出 ./parser" >&2; exit 1; }
check_conflicts "$JUDGE" "参考 Makefile"

cd "$REPO"
diffrun "$JUDGE/parser" "参考 Makefile"
[ "$LAB2_RAN" -ne 0 ] || { echo "FAIL  参考 Makefile 路径：Test/lab2 一个用例都没跑到" >&2; exit 1; }
[ "$DIFF_FAIL" -eq 0 ] || { echo "FAIL  参考 Makefile 路径：$DIFF_FAIL 个用例与仓库构建不一致" >&2; exit 1; }
echo "  ⑥ 参考 Makefile（摊平源码）行为对拍：$DIFF_PASS 个用例逐字节一致，冲突数 3"

# ── ⑦ 守卫：数目不为 0（语料被清空时不要报成功）────────────────
if [ "$DIFF_PASS" -eq 0 ]; then
    echo "FAIL  一个用例都没跑到 —— 检查 Test/ 是否被移动或清空" >&2
    exit 1
fi
other=$(find Test -name '*.cmm' -not -path 'Test/sample/*' -not -path 'Test/err/*' \
        -not -path 'Test/lab2/*' 2>/dev/null)
if [ -n "$other" ]; then
    echo "  NOTE  以下 .cmm 不在对拍范围内（由各自的单测目标负责）："
    echo "$other" | sed 's/^/        /'
fi

echo "──────────────────────────────────────────"
echo "交付包复核通过：$(basename "$ZIP")"
echo "  · 自建 Makefile 与**判分机用的参考 Makefile** 两条路径均可从零构建"
echo "  · 两条构建的产物都与仓库构建逐字节同行为（各 $DIFF_PASS 个用例）"
